class ApiException implements Exception {
  final String message;
  final int? statusCode;
  ApiException(this.message, {this.statusCode});

  @override
  String toString() => message;
}

class UserProfile {
  final String name;
  final String cityName;
  final String userOtp;
  final String profileImage;

  UserProfile({required this.name, required this.cityName, required this.userOtp, required this.profileImage});

  /// Users created through `api/auth/authenticate` get the default name "No name".
  bool get needsName => name.trim().isEmpty || name == 'No name';

  factory UserProfile.fromJson(Map<String, dynamic> json) => UserProfile(
        name: (json['name'] ?? '').toString(),
        cityName: (json['cityName'] ?? '').toString(),
        userOtp: (json['userOtp'] ?? '').toString(),
        profileImage: (json['profileImage'] ?? json['profileImg'] ?? '').toString(),
      );
}

class ShopSearchResult {
  final List<Shop> shops;
  final List<Map<String, dynamic>> matchedProducts;
  ShopSearchResult(this.shops, this.matchedProducts);
}

/// Every call to gotanbackend (`Common.baseUrl`) and the Digistall commerce
/// backend (`Common.digiBaseUrl`) goes through here.
class Api {
  static const _timeout = Duration(seconds: 25);
  static const _json = {'Content-Type': 'application/json'};

  // ---------------------------------------------------------------- plumbing

  static Future<dynamic> _send(Future<http.Response> Function() request) async {
    final http.Response response;
    try {
      response = await request().timeout(_timeout);
    } on SocketException {
      throw ApiException('No internet connection. Please check your network.');
    } on TimeoutException {
      throw ApiException('The server is taking too long. Please try again.');
    } on http.ClientException {
      throw ApiException('Could not reach the server. Please try again.');
    }

    dynamic body;
    if (response.body.trim().isNotEmpty) {
      try {
        body = jsonDecode(response.body);
      } catch (_) {
        body = response.body;
      }
    }

    if (response.statusCode >= 200 && response.statusCode < 300) return body;

    String message = 'Something went wrong (${response.statusCode}).';
    if (body is Map) {
      final m = body['message'] ?? body['error'] ?? body['response'];
      if (m is String && m.isNotEmpty) message = m;
    } else if (body is String && body.isNotEmpty && body.length < 120) {
      message = body;
    }
    throw ApiException(message, statusCode: response.statusCode);
  }

  static Future<dynamic> _post(String base, String path, Map<String, dynamic> body, {Map<String, String>? query}) {
    final uri = Uri.parse(base + path).replace(queryParameters: query);
    return _send(() => http.post(uri, headers: _json, body: jsonEncode(body)));
  }

  static Future<dynamic> _get(String base, String path, {Map<String, String>? query}) {
    final uri = Uri.parse(base + path).replace(queryParameters: query);
    return _send(() => http.get(uri, headers: _json));
  }

  static Map<String, dynamic>? _asMap(dynamic v) => v is Map ? v.cast<String, dynamic>() : null;

  // -------------------------------------------------------------------- auth

  /// Logs in or registers a phone number (after Firebase OTP) and stores the
  /// FCM token. New users get a 4-digit ride OTP generated by the backend.
  static Future<void> authenticate(String phone, {String? deviceToken}) async {
    await _post(Common.baseUrl, 'api/auth/authenticate', {
      'phoneNumber': phone,
      'cityName': Common.cityName,
      if (deviceToken != null && deviceToken.isNotEmpty) 'deviceToken': deviceToken,
    });
  }

  static Future<UserProfile> getUser(String phone) async {
    final body = await _post(Common.baseUrl, 'api/user/getuser', {'phoneNumber': phone});
    return UserProfile.fromJson(_asMap(body) ?? const {});
  }

  /// Throws [ApiException] with the backend reason ("User not found",
  /// "Invalid password") when login fails.
  static Future<void> loginWithPassword(String phone, String password) async {
    await _post(Common.baseUrl, 'api/auth/loginuserwithpassword', {'phoneNumber': phone, 'password': password});
  }

  static Future<void> setPassword(String phone, String password) async {
    await _post(Common.baseUrl, 'api/auth/adduserpassword', {'phoneNumber': phone, 'password': password});
  }

  static Future<void> updateName(String phone, String name) async {
    await _post(Common.baseUrl, 'api/auth/newname', {'phoneNumber': phone, 'name': name});
  }

  static Future<String> uploadProfileImage(String phone, File image) async {
    final request = http.MultipartRequest('POST', Uri.parse('${Common.baseUrl}api/auth/uploadImage'))
      ..fields['phoneNumber'] = phone
      ..files.add(await http.MultipartFile.fromPath('ProfileImg', image.path));
    final body = await _send(() async => http.Response.fromStream(await request.send()));
    final url = _asMap(body)?['data']?.toString() ?? '';
    if (url.isEmpty) throw ApiException('Upload failed. Please try again.');
    return url;
  }

  static Future<void> deleteAccount(String phone) async {
    await _post(Common.baseUrl, 'api/auth/deleteuser', {'phoneNumber': phone});
  }

  // ------------------------------------------------------------------- shops

  static Future<ShopSearchResult> getShops({String search = '', String tag = 'All', String? format}) async {
    final body = await _get(Common.baseUrl, 'api/shop/getallshops', query: {
      'cityName': Common.cityName,
      if (search.trim().isNotEmpty) 'search': search.trim(),
      if (tag != 'All') 'tag': tag,
      if (format != null && format.isNotEmpty) 'format': format,
    });
    final map = _asMap(body) ?? const {};
    final shops = (map['shops'] as List? ?? const [])
        .whereType<Map>()
        .map((s) => Shop.fromJson(s.cast<String, dynamic>()))
        .where((s) => s.shopId.isNotEmpty)
        .toList();
    final products =
        (map['matchedProducts'] as List? ?? const []).whereType<Map>().map((p) => p.cast<String, dynamic>()).toList();
    return ShopSearchResult(shops, products);
  }

  /// Increments and returns the gotan.in visitor counter.
  static Future<int?> visitCount() async {
    final body = await _get(Common.baseUrl, 'api/counter/gotanCounter');
    return body is num ? body.toInt() : int.tryParse('$body');
  }

  /// Returns null when the shop has no Digistall store.
  static Future<Store?> getStore(String shopId) async {
    final body = await _post(Common.digiBaseUrl, 'shop', {'shopId': shopId});
    final response = _asMap(_asMap(body)?['response']);
    return response == null ? null : Store.fromJson(response);
  }

  // ------------------------------------------------------- rides and parcels

  static String _addPath(BookingKind k) => k == BookingKind.ride ? 'api/user/addriderorder' : 'api/user/addParcelOrder';
  static String _acceptPath(BookingKind k) =>
      k == BookingKind.ride ? 'api/user/acceptBookRiderOrder' : 'api/user/acceptBookParcelOrder';
  static String _rejectPath(BookingKind k) =>
      k == BookingKind.ride ? 'api/user/rejectBookRiderOrder' : 'api/user/rejectBookParcelOrder';
  static String _currentPath(BookingKind k) =>
      k == BookingKind.ride ? 'api/user/getCurrentRiderOrder' : 'api/user/getCurrentParcelOrder';
  static String _historyPath(BookingKind k) => k == BookingKind.ride ? 'api/user/myRiderOrder' : 'api/user/myParcelOrder';

  /// Creates the booking in "Pending" state and returns its id.
  static Future<String> createBooking(BookingKind kind, String phone, Map<String, dynamic> orderDetails) async {
    final body = await _post(Common.baseUrl, _addPath(kind), {'phoneNumber': phone, 'orderDetails': orderDetails});
    final id = _asMap(body)?['orderId']?.toString() ?? '';
    if (id.isEmpty) throw ApiException('Could not create the booking. Please try again.');
    return id;
  }

  /// Confirms the price and publishes the booking to riders. The backend looks
  /// the user up by phone *and* city, so [cityName] must be the user's stored city.
  static Future<void> confirmBooking(
    BookingKind kind, {
    required String phone,
    required String orderId,
    required int price,
    required String distance,
    required String cityName,
  }) async {
    await _post(
      Common.baseUrl,
      _acceptPath(kind),
      {'phoneNumber': phone, 'orderId': orderId, 'expectedPrice': price, 'distance': distance},
      query: {'cityName': cityName},
    );
  }

  static Future<void> cancelBooking(BookingKind kind, String phone, String orderId) async {
    await _post(Common.baseUrl, _rejectPath(kind), {'phoneNumber': phone, 'orderId': orderId});
  }

  static Future<Booking?> getBooking(BookingKind kind, String phone, String orderId) async {
    final body = await _post(Common.baseUrl, _currentPath(kind), {'phoneNumber': phone, 'orderId': orderId});
    final map = _asMap(body);
    return map == null ? null : Booking.fromJson(kind, map);
  }

  static Future<List<Booking>> bookingHistory(BookingKind kind, String phone) async {
    final body = await _post(Common.baseUrl, _historyPath(kind), {'phoneNumber': phone});
    final list = body is List ? body : const [];
    return list.whereType<Map>().map((m) => Booking.fromJson(kind, m.cast<String, dynamic>())).toList().reversed.toList();
  }

  // -------------------------------------------------------------- shop orders

  /// Places a Digistall order. Returns the new order id. The backend answers
  /// 409 when any item is out of stock.
  static Future<String> placeOrder(Map<String, dynamic> payload) async {
    try {
      final body = await _post(Common.digiBaseUrl, 'customer/addorder', payload);
      return _asMap(body)?['orderId']?.toString() ?? '';
    } on ApiException catch (e) {
      if (e.statusCode == 409) {
        throw ApiException('Some items are out of stock or no longer available. Please update your cart.',
            statusCode: 409);
      }
      if (e.statusCode == 504) {
        throw ApiException('The shop could not take this order right now. Please try again.', statusCode: 504);
      }
      rethrow;
    }
  }

  static Future<List<ShopOrder>> shopOrders(String? phone, List<String> orderIds) async {
    if ((phone == null || phone.isEmpty) && orderIds.isEmpty) return [];
    final body = await _post(Common.digiBaseUrl, 'customer/getorders', {
      if (phone != null && phone.isNotEmpty) 'phoneNumber': phone,
      if (orderIds.isNotEmpty) 'orderIds': orderIds,
    });
    return ShopOrder.groupFromJson(_asMap(body)?['orders'] as List? ?? const []);
  }

  /// Rider dispatch record created when the seller hands an order to a Gotan
  /// rider. Holds the OTP the customer gives the rider on delivery.
  static Future<Map<String, dynamic>?> riderDispatch(String orderId) async {
    final body = await _post(Common.baseUrl, 'api/digiorder/shopdigiorder', {'orderId': orderId});
    final list = _asMap(body)?['shopOrderDetail'];
    if (list is List && list.isNotEmpty && list.first is Map) return (list.first as Map).cast<String, dynamic>();
    return null;
  }
}
